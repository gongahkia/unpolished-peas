import assert from "node:assert/strict";
import {createBrowserArtifacts, artifactLimits} from "../src/browser/artifacts.mjs";

const canvas = {toDataURL(type) { assert.equal(type, "image/png"); return "data:image/png;base64,AA=="; }};
const artifacts = createBrowserArtifacts({canvas});
const memory = new WebAssembly.Memory({initial: 1});
new TextEncoder().encodeInto("shader compilation failed", new Uint8Array(memory.buffer));
assert.equal(artifacts.emit(memory, 0, 25), true);
assert.equal(artifacts.emit(memory, memory.buffer.byteLength, 1), false);
artifacts.recordTrace({name: "draw", ph: "X", ts: 1, dur: 2});
artifacts.recordCommand({tag: "rect", x: 1, y: 2});
artifacts.setRendererDiagnostic({version: 1, requested_renderer: "webgl2"});
assert.equal(artifacts.captureFrame(), "data:image/png;base64,AA==");
const values = artifacts.snapshot();
assert.deepEqual(values.map(({name}) => name), ["screenshot.png", "renderer-diagnostics.json", "diagnostics.json", "trace.json", "commands.json", "logging.json"]);
assert.deepEqual(JSON.parse(values[1].data), {version: 1, requested_renderer: "webgl2"});
assert.deepEqual(JSON.parse(values[2].data), {version: 1, messages: ["shader compilation failed"]});
assert.deepEqual(JSON.parse(values[3].data), {displayTimeUnit: "ms", traceEvents: [{name: "draw", ph: "X", ts: 1, dur: 2}]});
assert.deepEqual(JSON.parse(values[4].data), {version: 1, commands: [{tag: "rect", x: 1, y: 2}]});

// Failed canvas serialization must not become a PNG artifact or replace the
// last successful capture with an empty data URL.
canvas.toDataURL = () => "data:,";
assert.equal(artifacts.captureFrame(), null);
assert.deepEqual(artifacts.snapshot()[0], values[0]);
const empty = createBrowserArtifacts({canvas});
assert.equal(empty.captureFrame(), null);
assert.equal(empty.snapshot().some(({name}) => name === "screenshot.png"), false);

// Bound long sessions, preserve newest records, and take ownership of objects.
const bounded = createBrowserArtifacts({canvas, limits: {...artifactLimits, messages: 2, traces: 2, commands: 2, messageBytes: 32, recordBytes: 64, screenshotBytes: 64}});
const command = {tag: "rect", x: 1};
bounded.recordCommand(command);
command.x = 99;
bounded.recordCommand({tag: "rect", x: 2});
bounded.recordCommand({tag: "rect", x: 3});
for (let i = 0; i < 10; i += 1) bounded.recordTrace({name: "frame", ts: i});
assert.equal(bounded.recordTrace({name: "x".repeat(100)}), false);
const circular = {}; circular.self = circular;
assert.equal(bounded.recordCommand(circular), false);
assert.equal(bounded.emit(memory, 0, 33), false);
for (let i = 0; i < 4; i += 1) assert.equal(bounded.emit(memory, 0, 25), true);
const snapshot = Object.fromEntries(bounded.snapshot().map(({name, data}) => [name, JSON.parse(data)]));
assert.deepEqual(snapshot["commands.json"].commands, [{tag: "rect", x: 2}, {tag: "rect", x: 3}]);
assert.deepEqual(snapshot["trace.json"].traceEvents.map(({ts}) => ts), [8, 9]);
assert.equal(snapshot["logging.json"].retention.trace.dropped, 8);
assert.equal(snapshot["logging.json"].retention.trace.rejected, 1);
assert.equal(snapshot["logging.json"].retention.commands.dropped, 1);
assert.equal(snapshot["logging.json"].retention.commands.rejected, 1);
assert.equal(snapshot["logging.json"].retention.diagnostics.dropped, 2);
assert.equal(snapshot["logging.json"].retention.diagnostics.rejected, 1);
const owned = createBrowserArtifacts();
const ownedCommand = {tag: "clear", color: [1, 2, 3]};
owned.recordCommand(ownedCommand);
ownedCommand.color[0] = 99;
assert.equal(JSON.parse(owned.snapshot().find(({name}) => name === "commands.json").data).commands[0].color[0], 1);
canvas.toDataURL = () => "data:image/png;base64," + "A".repeat(100);
assert.equal(bounded.captureFrame(), null);
assert.equal(JSON.parse(bounded.snapshot().find(({name}) => name === "logging.json").data).retention.screenshot.rejected, 1);
assert.throws(() => createBrowserArtifacts({limits: {...artifactLimits, traces: 0}}), /invalid_artifact_limits/);
console.log("browser artifacts passed: bounded records, owned snapshots, rejected payloads and visible retention counts");

let clockCalls = 0;
const disabled = createBrowserArtifacts({clock: () => { clockCalls += 1; return 0; }});
assert.equal(disabled.log("err", "engine", "ignored"), false);
assert.equal(disabled.failure("draw", "ignored"), null);
disabled.beginFrame();
assert.equal(clockCalls, 0, "disabled logging never reads its clock");
let timestamp = 100;
const events = createBrowserArtifacts({logging: {level: "warn", categories: ["render"], sessionId: 42}, clock: () => timestamp});
assert.equal(events.log("info", "render", "hidden"), false);
assert.equal(events.log("err", "audio", "hidden"), false);
timestamp = 100.25;
events.beginFrame();
assert.equal(events.log("warn", "render", "ready", {count: 2, cached: true}), true);
let lines = events.snapshot().find(({name}) => name === "events.jsonl").data.trim().split("\n").map(JSON.parse);
assert.deepEqual(lines, [{version: 1, timestamp_ns: 250000, session_id: 42, frame_id: 1, level: "warn", category: "render", message: "ready", fields: {count: 2, cached: true}}]);
assert.equal(events.log("verbose", "render", "invalid"), false);
assert.equal(events.log("err", "render", "invalid", {floating: 1.5}), false);
assert.equal(events.log("err", "render", "✓".repeat(1024)), true);
lines = events.snapshot().find(({name}) => name === "events.jsonl").data.trim().split("\n").map(JSON.parse);
assert.equal(lines.at(-1).message.length, 341);
assert.equal(lines.at(-1).message.includes("�"), false);
for (let i = 0; i < 300; i += 1) events.log("err", "render", "retained-" + i);
const files = () => Object.fromEntries(events.snapshot().map(({name, data}) => [name, data]));
assert.equal(files()["events.jsonl"].trim().split("\n").length, 128);
assert.equal(JSON.parse(files()["logging.json"]).events.dropped_events, 174);
assert.equal(JSON.parse(files()["logging.json"]).events.truncated_values, 1);
assert.equal(JSON.parse(files()["logging.json"]).events.rejected_events, 2);
for (let i = 0; i < 6; i += 1) events.failure("draw", "OriginalError" + i, "game.draw");
const retainedIncidents = Object.keys(files()).filter((name) => name.startsWith("incident-"));
assert.deepEqual(retainedIncidents, ["incident-42-3.json", "incident-42-4.json", "incident-42-5.json", "incident-42-6.json"]);
assert.equal(JSON.parse(files()["incident-42-6.json"]).error, "OriginalError5");
assert.equal(JSON.parse(files()["incident-42-6.json"]).operation, "game.draw");
assert.equal(JSON.parse(files()["incident-42-6.json"]).screenshot, null);
assert.equal(JSON.parse(files()["logging.json"]).events.dropped_incidents, 2);
assert.equal(events.failure("draw", {toString() { throw new Error("must not replace original failure"); }}), null);
console.log("browser structured logs passed: native-compatible records, filtering, Unicode bounds, no disabled clocks and four distinct incidents");
