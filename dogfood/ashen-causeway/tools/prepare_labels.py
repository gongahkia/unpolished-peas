"""Refresh the finite static text catalog after editing game copy."""
from pathlib import Path
import re
import json
root = Path(__file__).resolve().parents[1]
labels = {'BELL', 'PASSAGE', 'E - REST', 'E - RING', 'E - LIFT', 'E - OPEN', 'Health', 'Stamina', 'Flasks', 'Embers'}
for name in ('game.zig', 'world.zig'):
    for literal in re.findall(r'"(?:[^"\\]|\\.)*"', (root / 'src' / name).read_text()):
        value = json.loads(literal)
        if '{' not in value and (' ' in value or value.isupper()):
            labels.add(value)
(root / 'src' / 'labels.zig').write_text('// Generated by tools/prepare_labels.py; no runtime allocation.\npub const labels = [_][]const u8{\n' + ''.join('    ' + json.dumps(label, ensure_ascii=True) + ',\n' for label in sorted(labels)) + '};\n')
